package com.securebank.pdf;

import com.securebank.model.AccountInfo;
import com.securebank.model.Transaction;
import com.securebank.pdf.PdfWriter.Font;

import java.io.IOException;
import java.math.BigDecimal;
import java.nio.file.Path;
import java.text.DecimalFormat;
import java.text.DecimalFormatSymbols;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.time.temporal.ChronoUnit;
import java.util.List;
import java.util.Locale;

public final class StatementExporter {

    private static final float LEFT = 50, RIGHT = PdfWriter.PAGE_WIDTH - 50, BOTTOM = 70, ROW = 15;
    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    private StatementExporter() { }

    public static void export(String owner, AccountInfo acc, List<Transaction> txs, Path target) throws IOException {
        DecimalFormat money = new DecimalFormat("#,##0.00", DecimalFormatSymbols.getInstance(Locale.ROOT));
        PdfWriter pdf = new PdfWriter();
        pdf.setTitle("Account Statement " + acc.number());

        float y = 790;
        pdf.text(Font.BOLD, 20, LEFT, y, "Secure Banking Application");
        pdf.text(Font.REGULAR, 12, LEFT, y - 20, "Account Statement");
        pdf.line(LEFT, y - 30, RIGHT, y - 30, 1.2f);

        y -= 56;
        String[][] info = {
            {"Account holder", owner},
            {"Account number", acc.number()},
            {"Account type", acc.type().name()},
            {"Opened", acc.createdAt().format(STAMP)},
            {"Statement date", LocalDateTime.now().truncatedTo(ChronoUnit.SECONDS).format(STAMP)},
            {"Current balance", money.format(acc.balance())},
        };
        for (String[] row : info) {
            pdf.text(Font.BOLD, 10.5f, LEFT, y, row[0] + ":");
            pdf.text(Font.REGULAR, 10.5f, LEFT + 110, y, row[1]);
            y -= 16;
        }

        y -= 14;
        pdf.text(Font.BOLD, 12, LEFT, y, "Transaction history");
        y -= 26;
        y = tableHeader(pdf, y);

        BigDecimal in = BigDecimal.ZERO, out = BigDecimal.ZERO;
        if (txs.isEmpty()) {
            pdf.text(Font.REGULAR, 10, LEFT + 4, y, "No transactions recorded.");
            y -= ROW;
        }
        for (Transaction t : txs) {
            if (y < BOTTOM) {
                footer(pdf);
                pdf.newPage();
                pdf.text(Font.REGULAR, 9, LEFT, 800, "Account " + acc.number() + " - statement (continued)");
                y = tableHeader(pdf, 780);
            }
            boolean debit = t.type() == Transaction.Type.WITHDRAWAL;
            if (debit) out = out.add(t.amount()); else in = in.add(t.amount());
            String amount = (debit ? "-" : "+") + money.format(t.amount());
            String rowText = String.format(Locale.ROOT, "%-19s %-8s %-10s %14s %14s",
                    t.timestamp().format(STAMP), t.id(), t.type().name(), amount, money.format(t.balanceAfter()));
            pdf.text(Font.MONO, 9, LEFT + 4, y, rowText);
            y -= ROW;
        }

        if (y < BOTTOM + 40) {
            footer(pdf);
            pdf.newPage();
            y = 780;
        }
        pdf.line(LEFT, y + 6, RIGHT, y + 6, 0.6f);
        y -= 12;
        pdf.text(Font.BOLD, 10, LEFT, y, "Total credits: " + money.format(in));
        pdf.text(Font.BOLD, 10, LEFT + 200, y, "Total debits: " + money.format(out));
        footer(pdf);

        pdf.writeTo(target);
    }

    private static float tableHeader(PdfWriter pdf, float y) {
        pdf.rect(LEFT, y - 4, RIGHT - LEFT, 16, 0.88f);
        pdf.text(Font.MONO, 9, LEFT + 4, y,
                String.format(Locale.ROOT, "%-19s %-8s %-10s %14s %14s", "Date / time", "Ref", "Type", "Amount", "Balance"));
        return y - 20;
    }

    private static void footer(PdfWriter pdf) {
        pdf.line(LEFT, 52, RIGHT, 52, 0.5f);
        pdf.text(Font.REGULAR, 8, LEFT, 40, "Generated by Secure Banking Application. Keep this statement confidential.");
        pdf.text(Font.REGULAR, 8, RIGHT - 40, 40, "Page " + pdf.pageCount());
    }
}
